CREATE TABLE app.audit_log (
    audit_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name      text NOT NULL,
    record_pk       text NOT NULL,
    operation       text NOT NULL CHECK (operation IN ('INSERT', 'UPDATE', 'DELETE')),
    old_data        jsonb,
    new_data        jsonb,
    changed_at      timestamptz NOT NULL DEFAULT clock_timestamp(),
    changed_by      text NOT NULL DEFAULT session_user,
    application_name text DEFAULT current_setting('application_name', true),
    transaction_id  bigint NOT NULL DEFAULT txid_current()
);
CREATE INDEX idx_audit_log_table_pk_time ON app.audit_log (table_name, record_pk, changed_at DESC);
CREATE INDEX idx_audit_log_changed_at ON app.audit_log (changed_at DESC);

CREATE OR REPLACE FUNCTION app.capture_audit_event()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
DECLARE
    v_row jsonb;
    v_pk  text;
BEGIN
    IF TG_OP = 'DELETE' THEN
        v_row := to_jsonb(OLD);
    ELSE
        v_row := to_jsonb(NEW);
    END IF;
    v_pk := CASE TG_TABLE_NAME
        WHEN 'customers' THEN v_row ->> 'customer_id'
        WHEN 'products' THEN v_row ->> 'product_id'
        WHEN 'inventory' THEN v_row ->> 'product_id'
        WHEN 'orders' THEN v_row ->> 'order_id'
        WHEN 'order_items' THEN v_row ->> 'order_item_id'
        WHEN 'inventory_movements' THEN v_row ->> 'movement_id'
        ELSE 'unknown'
    END;
    INSERT INTO app.audit_log (
        table_name, record_pk, operation, old_data, new_data,
        changed_by, application_name, transaction_id
    ) VALUES (
        format('%I.%I', TG_TABLE_SCHEMA, TG_TABLE_NAME),
        v_pk,
        TG_OP,
        CASE WHEN TG_OP IN ('UPDATE', 'DELETE') THEN to_jsonb(OLD) ELSE NULL END,
        CASE WHEN TG_OP IN ('INSERT', 'UPDATE') THEN to_jsonb(NEW) ELSE NULL END,
        session_user,
        current_setting('application_name', true),
        txid_current()
    );
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$function$;

CREATE TRIGGER trg_audit_customers AFTER INSERT OR UPDATE OR DELETE ON app.customers
FOR EACH ROW EXECUTE FUNCTION app.capture_audit_event();
CREATE TRIGGER trg_audit_products AFTER INSERT OR UPDATE OR DELETE ON app.products
FOR EACH ROW EXECUTE FUNCTION app.capture_audit_event();
CREATE TRIGGER trg_audit_inventory AFTER INSERT OR UPDATE OR DELETE ON app.inventory
FOR EACH ROW EXECUTE FUNCTION app.capture_audit_event();
CREATE TRIGGER trg_audit_orders AFTER INSERT OR UPDATE OR DELETE ON app.orders
FOR EACH ROW EXECUTE FUNCTION app.capture_audit_event();
CREATE TRIGGER trg_audit_order_items AFTER INSERT OR UPDATE OR DELETE ON app.order_items
FOR EACH ROW EXECUTE FUNCTION app.capture_audit_event();
CREATE TRIGGER trg_audit_inventory_movements AFTER INSERT OR UPDATE OR DELETE ON app.inventory_movements
FOR EACH ROW EXECUTE FUNCTION app.capture_audit_event();

