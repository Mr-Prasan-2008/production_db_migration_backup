\set ON_ERROR_STOP on
CREATE SCHEMA IF NOT EXISTS app;
CREATE TABLE IF NOT EXISTS app.schema_migrations (
    version      varchar(20) PRIMARY KEY,
    description  text NOT NULL,
    applied_at   timestamptz NOT NULL DEFAULT clock_timestamp()
);
SELECT EXISTS (SELECT 1 FROM app.schema_migrations WHERE version = '001') AS migration_applied \gset
\if :migration_applied
    \echo 'Migration 001 already applied; skipping core schema.'
\else
BEGIN;
CREATE TABLE app.customers (
    customer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name   text NOT NULL CHECK (length(btrim(full_name)) > 0),
    email       text NOT NULL CHECK (length(btrim(email)) > 0),
    is_active   boolean NOT NULL DEFAULT true,
    created_at  timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at  timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE UNIQUE INDEX ux_customers_email_lower ON app.customers (lower(email));

CREATE TABLE app.products (
    product_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku          text NOT NULL UNIQUE CHECK (length(btrim(sku)) > 0),
    product_name text NOT NULL CHECK (length(btrim(product_name)) > 0),
    unit_price   numeric(12,2) NOT NULL CHECK (unit_price > 0),
    is_active    boolean NOT NULL DEFAULT true,
    created_at   timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at   timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE app.inventory (
    product_id       bigint PRIMARY KEY REFERENCES app.products(product_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    quantity_on_hand integer NOT NULL DEFAULT 0 CHECK (quantity_on_hand >= 0),
    updated_at       timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE app.orders (
    order_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_reference text NOT NULL UNIQUE CHECK (length(btrim(order_reference)) > 0),
    customer_id    bigint NOT NULL REFERENCES app.customers(customer_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    status         text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'fulfilled', 'cancelled')),
    ordered_at     timestamptz NOT NULL DEFAULT clock_timestamp(),
    fulfilled_at   timestamptz,
    created_at     timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at     timestamptz NOT NULL DEFAULT clock_timestamp(),
    CHECK ((status = 'fulfilled') = (fulfilled_at IS NOT NULL))
);

CREATE TABLE app.order_items (
    order_item_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      bigint NOT NULL REFERENCES app.orders(order_id) ON UPDATE CASCADE ON DELETE CASCADE,
    product_id    bigint NOT NULL REFERENCES app.products(product_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    quantity      integer NOT NULL CHECK (quantity > 0),
    unit_price    numeric(12,2) NOT NULL CHECK (unit_price > 0),
    line_total    numeric(14,2) GENERATED ALWAYS AS (quantity * unit_price) STORED,
    created_at    timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (order_id, product_id)
);

CREATE TABLE app.inventory_movements (
    movement_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id      bigint NOT NULL REFERENCES app.products(product_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    delta_quantity  integer NOT NULL CHECK (delta_quantity <> 0),
    reason          text NOT NULL CHECK (length(btrim(reason)) > 0),
    reference_key   text UNIQUE,
    created_at      timestamptz NOT NULL DEFAULT clock_timestamp(),
    created_by      text NOT NULL DEFAULT session_user
);

CREATE INDEX idx_orders_customer_ordered_at ON app.orders (customer_id, ordered_at DESC);
CREATE INDEX idx_order_items_product ON app.order_items (product_id);
CREATE INDEX idx_inventory_movements_product_time ON app.inventory_movements (product_id, created_at DESC);
CREATE INDEX idx_orders_pending_ordered_at ON app.orders (ordered_at) WHERE status = 'pending';

INSERT INTO app.schema_migrations (version, description)
VALUES ('001', 'Core customer, product, order, inventory and movement schema')
ON CONFLICT (version) DO NOTHING;
COMMIT;
\endif
